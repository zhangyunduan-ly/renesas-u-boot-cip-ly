void hw_wdt_feed(void)
{
	if (feed_dog_index % 2) {
		gpio_direction_output(WDT_GPIO, 1); //high
	} else {
		gpio_direction_output(WDT_GPIO, 0); //low
	}
	feed_dog_index++;
}

