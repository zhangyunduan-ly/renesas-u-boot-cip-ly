static inline int st75161_write_cmd(unsigned char ch)
{
	unsigned char i;

	gpio_set_value(A0_GPIO, 0); 

	for (i = 0; i < 8; i++) {
		gpio_set_value(ST75161_CLK_GPIO, 0); 
		gpio_set_value(ST75161_MOSI_GPIO, !!(ch & (0x80 >> i))); 
		gpio_set_value(ST75161_CLK_GPIO, 1); 
	}
	
	return 0;
}

static inline int st75161_write_dat(unsigned char ch)
{
	unsigned char i;

	gpio_set_value(A0_GPIO, 1);
	
	for (i = 0; i < 8; i++) {
		gpio_set_value(ST75161_CLK_GPIO, 0); 
		gpio_set_value(ST75161_MOSI_GPIO, !!(ch & (0x80 >> i))); 
		gpio_set_value(ST75161_CLK_GPIO, 1); 
	}

	return 0;
}

static int st75161_init(void)
{
	unsigned char i, j;
	unsigned char TW_Buf[LCD_Seg];
	int lop = 0;

	/* st75161 set pin */
	gpio_request(ST75161_CLK_GPIO, "LCD_CLK");
	gpio_request(ST75161_MOSI_GPIO, "LCD_MOSI");
	gpio_request(A0_GPIO, "LCD_A0");
	gpio_request(CSB_GPIO, "LCD_CSB");
	gpio_request(RSTB_GPIO, "LCD_RTSB");
	gpio_request(BL_GPIO, "LCD_BL");
	gpio_direction_output(ST75161_CLK_GPIO, 1);
	gpio_direction_output(ST75161_MOSI_GPIO, 1);
	gpio_direction_output(A0_GPIO, 1);
	gpio_direction_output(CSB_GPIO, 1);
	gpio_direction_output(RSTB_GPIO, 1);
	gpio_direction_output(BL_GPIO, 1);

	/* st75161 reset */	
	gpio_set_value(RSTB_GPIO, 0);
	mdelay(20);
	gpio_set_value(RSTB_GPIO, 1);
	mdelay(20);

	/* st75161 register init */
	gpio_set_value(CSB_GPIO, 0);
	udelay(1);
	st75161_write_cmd(0x31);		// Extension Command 2
	st75161_write_cmd(0xD7);		// Disable Auto Read

	st75161_write_dat(0x9F);

	st75161_write_cmd(0xE0);		// Enable OTP read
	st75161_write_dat(0x00);		// Disable Auto Read
	udelay(40);

	st75161_write_cmd(0xE3);		// OTP Up-Load
	udelay(40);

	st75161_write_cmd(0xE1);		// OTP Control Out

	st75161_write_cmd(0x30);		// Extension Command 1
	st75161_write_cmd(0x94);		// Sleep out
	st75161_write_cmd(0xD1);		// Turns on the internal oscillation circuit.
	st75161_write_cmd(0xAE);		// display off
	udelay(20);

	st75161_write_cmd(0xA6);		// Normal Display
	st75161_write_cmd(0xCA);		// Displsy Control
	st75161_write_dat(0x00);		// CL Dividing Ratio:Not Divide
	st75161_write_dat(0x9F);		// Duty Set:160 Duty
	st75161_write_dat(0x00);		// Nline=

	st75161_write_cmd(0xBC);		// Data Scan Direction
	st75161_write_dat(0x00);		// MV=0,MX=0

	st75161_write_cmd(0xAB);		//Start line address
	st75161_write_dat(0x00);

	st75161_write_cmd(0x20);		// Power Control
	st75161_write_dat(0x0B);		// VB, VR,VF All ON

	st75161_write_cmd(0x81);		// set Vop

	st75161_write_dat(0x20);		// Vop[5:0]  14.5V    1/12  0x30
	st75161_write_dat(0x04);		// Vop[8:6]

	st75161_write_cmd(0x0C);		// LSB on top      20190924
	st75161_write_cmd(0xF0);		// Display Mode     20190924
	st75161_write_dat(0x10);		// Mono Mode        20190924
	st75161_write_cmd(0x76);		// ICON=0 ; Disable ICON RAM.

	st75161_write_cmd(0x31);		// Extension Command 2
	st75161_write_cmd(0x32);		// Analog Circuit Set
	st75161_write_dat(0x00);
	st75161_write_dat(0x01);		// Booster Efficiency =6KHz
	st75161_write_dat(0x03);		// 1/11 Bias

	st75161_write_cmd(0x51);		// Booster Level Set
	st75161_write_dat(0xFB);		// 10 Times

	st75161_write_cmd(0x40);		// Internal Power Supply
	st75161_write_cmd(0xF0);		// Frame Rate
	st75161_write_dat(0x03);		// FA=34.5Hz 0x03
	st75161_write_dat(0x07);		// FB=49Hz
	st75161_write_dat(0x0C);		// FC=69Hz
	st75161_write_dat(0x14);		// FD=83Hz

	st75161_write_cmd(0xF2);		// Temperature Range
	st75161_write_dat(0x0F);		// TA=-25
	st75161_write_dat(0x28);		// TB=0
	st75161_write_dat(0x5A);		// TC=50

	st75161_write_cmd(0xF4);		// Temperature Gradient Compensation
	st75161_write_dat(0xAF);		// MT1=7,MT0=15   6F
	st75161_write_dat(0x11);		// MT3=2,MT2=2	22
	st75161_write_dat(0x11);		// MT5=1,MT4=1
	st75161_write_dat(0x02);		// MT7=0,MT6=2
	st75161_write_dat(0x00);		// MT9=0,MT8=0
	st75161_write_dat(0x32);		// MTB=3,MTA=2
	st75161_write_dat(0x82);		// MTD=8,MTC=2
	st75161_write_dat(0xB6);		// MTF=11,MTE=6

	st75161_write_cmd(0x30);		// Extension command 1

	/* For ESD Test 增加抗静电能力 */
	st75161_write_cmd(0x39);		// Extension Command 4 
	st75161_write_cmd(0xE8);		// Enhance ESD 
	st75161_write_dat(0x8D);
	st75161_write_dat(0x0D);
	st75161_write_cmd(0x31);		// Extension Command 2 
	st75161_write_cmd(0x51);		// Enhance ESD 
	st75161_write_dat(0xFB);		// Booster Level x10

	st75161_write_cmd(0x30);		// Extension Command 1 
	st75161_write_cmd(0x15);		// Column Address Setting 
	st75161_write_dat(0);			// Starting column address
	st75161_write_dat(159); 		// Ending column address

	st75161_write_cmd(0x75);		// Row Address Setting 
	st75161_write_dat(0x00);		// Starting page address 
	st75161_write_dat(0x13);		// Ending page address

	st75161_write_cmd(0x5c);		// Write data

	/* ST75161 Clear DDRAM */
	for (i = 0; i < LCD_Seg; i++) {
		TW_Buf[i] = 0x00;
	}
	for (i = 0; i < LCD_Com / 8; i++) {
		for (j = 0; j < LCD_Seg; j++) {
			st75161_write_dat(TW_Buf[j]);
		}
	}

	/* ST75161_SetArea x start 24, x end 135, y start 9, y end 10 */
 	st75161_write_cmd(0x30);		// Extension Command 1
	st75161_write_cmd(0x15);		// Column Address Setting
	st75161_write_dat(0);			// Starting column address
	st75161_write_dat(159);			// Ending column address

	st75161_write_cmd(0x75);		// Row Address Setting
	st75161_write_dat(0);			// Starting page address
	st75161_write_dat(19);			// Ending page address

	st75161_write_cmd(0x5c);		// Write data

	/* ST75161 send logo data */
	for (lop = 0; lop <= 19; lop++) {
        for (i = 0; i <= 159; i++) {
            st75161_write_dat(logo_sms_st75161[lop*160+i]);
        }
    }

	st75161_write_cmd(0xAF);	// Display ON

	gpio_set_value(CSB_GPIO, 1);
}

static void peripheral_init()
{
	/* avoid PLC_POWER_EN leak current */
	gpio_request(PLC_POWER_EN, "PLC_POWER");
	gpio_direction_output(PLC_POWER_EN, 0);

	/* open peripheral power */
	gpio_request(PERIPHERAL_POWER_GPIO, "PERIPHERAL_POWER");
	gpio_direction_output(PERIPHERAL_POWER_GPIO, 1);
	mdelay(10);

	/* No AC, open battery discharge*/
	gpio_request(PFI_GPIO, "PFI");
	gpio_request(BATTERY_DISCHARGE_GPIO, "BATTERY_DISCHARGE");
	gpio_direction_input(PFI_GPIO);
	if (gpio_get_value(PFI_GPIO)) {
		gpio_direction_output(BATTERY_DISCHARGE_GPIO, 0);
	} else {
		gpio_direction_output(BATTERY_DISCHARGE_GPIO, 1);
	}

	gpio_request(RUN_LED_GPIO, "RUN_LED");
	gpio_direction_output(RUN_LED_GPIO, 0);
	gpio_request(WIFI_POWER_GPIO, "WIFI_POWER");
	gpio_direction_output(WIFI_POWER_GPIO, 1);
	gpio_request(WIFI_EN_GPIO, "WIFI_EN");
	gpio_direction_output(WIFI_EN_GPIO, 0);
	// gpio_request(BT_EN_GPIO, "BT_EN");
	// gpio_direction_output(BT_EN_GPIO, 0);

	mdelay(100);

	gpio_direction_output(WIFI_POWER_GPIO, 0);
	udelay(2);
	gpio_direction_output(WIFI_EN_GPIO, 1);
}

void s_init(void)
{
	/* SD1 power control: P39_1 = 0; P39_2 = 1; */
	*(volatile u32 *)(PFC_PMC37) &= 0xFFFFFFF9; /* Port func mode 0b00 */
	*(volatile u32 *)(PFC_PM37) = (*(volatile u32 *)(PFC_PM37) & 0xFFFFFFC3) | 0x28; /* Port output mode 0b1010 */
#if CONFIG_TARGET_SMARC_RZG2L
	*(volatile u32 *)(PFC_P37) = (*(volatile u32 *)(PFC_P37) & 0xFFFFFFF9) | 0x6;	/* Port 39[2:1] output value 0b11*/
#else

	*(volatile u32 *)(PFC_P37) = (*(volatile u32 *)(PFC_P37) & 0xFFFFFFF9) | 0x4;	/* Port 39[2:1] output value 0b10*/
#endif

	/* can go in board_eht_init() once enabled */
	*(volatile u32 *)(ETH_CH0) = (*(volatile u32 *)(ETH_CH0) & 0xFFFFFFFC) | ETH_PVDD_3300;
	*(volatile u32 *)(ETH_CH1) = (*(volatile u32 *)(ETH_CH1) & 0xFFFFFFFC) | ETH_PVDD_3300;
	/* Enable RGMII for both ETH{0,1} */
	*(volatile u32 *)(ETH_MII_RGMII) = (*(volatile u32 *)(ETH_MII_RGMII) | 0x00000003);
	/* ETH CLK */
	*(volatile u32 *)(CPG_RESET_ETH) = 0x30003;
	/* I2C CLK */
	*(volatile u32 *)(CPG_RESET_I2C) = 0xF000F;
	/* I2C pin non GPIO enable */
	*(volatile u32 *)(I2C_CH1) = 0x01010101;

	*(volatile u32 *)(RPC_CMNCR) = 0x01FFF300;
}

static void board_usb_init(void)
{
	/*Enable USB*/
	(*(volatile u32 *)CPG_RST_USB) = 0x000f000f;
	(*(volatile u32 *)CPG_CLKON_USB) = 0x000f000f;

	/* Setup  */
	/* Disable GPIO Write Protect */
	(*(volatile u32 *)PFC_PWPR) &= ~(0x1u << 7);	/* PWPR.BOWI = 0 */
	(*(volatile u32 *)PFC_PWPR) |= (0x1u << 6);	/* PWPR.PFCWE = 1 */

	/* set P4_0 as Func.1 for VBUSEN */
	(*(volatile u8 *)PFC_PMC14) |= (0x1u << 0);	/* PMC14.b0 = 1 */
	(*(volatile u8 *)PFC_PFC14) &= ~(0x7u << 0);	/* PFC14.PFC0 = 0 */
	(*(volatile u8 *)PFC_PFC14) |= (0x1u << 0);

	/* set P5_0 as Func.1 for OVERCUR */
	(*(volatile u8 *)PFC_PMC15) |= (0x1u << 0);	/* PMC15.b0 = 1 */
	(*(volatile u8 *)PFC_PFC15) &= ~(0x7u << 0);	/* PFC15.PFC0 = 0 */
	(*(volatile u8 *)PFC_PFC15) |= (0x1u << 0);

	/* set P42_0 as Func.1 for VBUSEN */
	(*(volatile u8 *)PFC_PMC3A) |= (0x1u << 0);	/* PMC14.b0 = 1 */
	(*(volatile u8 *)PFC_PFC3A) &= ~(0xfu << 0);	/* PFC15.PFC0 = 0 */
	(*(volatile u8 *)PFC_PFC3A) |= (0x1u << 0);

	/* set P42_1 as Func.1 for OVERCUR */
	(*(volatile u8 *)PFC_PMC3A) |= (0x1u << 0);	/* PMC14.b1 = 1 */
	(*(volatile u8 *)PFC_PFC3A) &= ~(0xfu << 4);	/* PFC15.PFC1 = 0 */
	(*(volatile u8 *)PFC_PFC3A) |= (0x1u << 4);

	/* Enable write protect */
	(*(volatile u32 *)PFC_PWPR) &= ~(0x1u << 6);	/* PWPR.PFCWE = 0 */
	(*(volatile u32 *)PFC_PWPR) |= (0x1u << 7);	/* PWPR.BOWI = 1 */

	/*Enable 2 USB ports*/
	(*(volatile u32 *)USBPHY_RESET) = 0x00001000u;
	/*USB0 is HOST*/
	(*(volatile u32 *)(USB0_BASE + COMMCTRL)) = 0;
	/*USB1 is HOST*/
	(*(volatile u32 *)(USB1_BASE + COMMCTRL)) = 0;
	/* Set USBPHY normal operation (Function only) */
	(*(volatile u16 *)(USBF_BASE + LPSTS)) |= (0x1u << 14);		/* USBPHY.SUSPM = 1 (func only) */
	/* Overcurrent is not supported */
	(*(volatile u32 *)(USB0_BASE + HcRhDescriptorA)) |= (0x1u << 12);	/* NOCP = 1 */
	(*(volatile u32 *)(USB1_BASE + HcRhDescriptorA)) |= (0x1u << 12);	/* NOCP = 1 */
}

static int board_spinor_op_nvcr_setup(void)
{
	struct spi_slave *spi;
	uint8_t nvcr[NVCR_LENGTH];
	uint8_t write_enable_cmd = WRITE_ENABLE_CMD;
	uint8_t read_cmd = NVCR_READ_CMD;
	uint8_t write_cmd = NVCR_WRITE_CMD;
	int ret;

	/* Initialize SPI */
	spi = spi_setup_slave(0, 0, 1000000, SPI_MODE_0);
	if (!spi) {
		printf("Failed to set up SPI slave\n");
		return -1;
	}

	ret = spi_claim_bus(spi);
	if (ret) {
		printf("Failed to claim SPI bus\n");
		spi_free_slave(spi);
		return ret;
	}

	/* Read NVCR */
	ret = spi_xfer(spi, 8, &read_cmd, NULL, SPI_XFER_BEGIN);
	if (ret) {
		printf("Failed to send NVCR Read command: %d\n", ret);
		goto release_bus;
	}

	ret = spi_xfer(spi, 8 * NVCR_LENGTH, NULL, nvcr, SPI_XFER_END);
	if (ret) {
		printf("Failed to read NVCR: %d\n", ret);
		goto release_bus;
	}

	/* Clear bit 4 of the NVCR - RESET# on DQ3 */
	nvcr[0] &= NVCR_BIT4_MASK;

	/* Write enable */
	ret = spi_xfer(spi, 8, &write_enable_cmd, NULL, SPI_XFER_BEGIN | SPI_XFER_END);
	if (ret) {
		printf("Failed to send Write Enable command: %d\n", ret);
		goto release_bus;
	}

	/* Write NVCR */
	ret = spi_xfer(spi, 8, &write_cmd, NULL, SPI_XFER_BEGIN);
	if (ret) {
		printf("Failed to send NVCR Write command: %d\n", ret);
		goto release_bus;
	}

	ret = spi_xfer(spi, 8 * NVCR_LENGTH, nvcr, NULL, SPI_XFER_END);
	if (ret) {
		printf("Failed to write NVCR: %d\n", ret);
		goto release_bus;
	}

release_bus:
	spi_release_bus(spi);
	spi_free_slave(spi);
	return ret;
}

